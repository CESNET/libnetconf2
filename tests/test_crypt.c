/**
 * @brief Create a hash for the given password and setting.
 *
 * @param[in] password Password.
 * @param[in] setting Setting "$<id>$[rounds=N$]<salt>$".
 * @param[out] out Output buffer.
 * @param[out] out_len Capacity of @p out including the terminating NUL.
 * @return nc_crypt() return value.
 */
static int
test_crypt_create(const char *password, const char *setting, char *out, size_t out_len)
{
    struct nc_crypt c;

    memset(&c, 0, sizeof c);
    c.action = NC_CRYPT_CREATE;
    c.output = out;
    c.output_len = out_len;

    return nc_crypt(password, setting, &c);
}

/**
 * @brief Verify a password against a stored hash.
 *
 * @param[in] password Password.
 * @param[in] setting Complete stored hash.
 * @param[in] match_init Initial value of the match result, to check that it is always set.
 * @param[out] match Resulting match value.
 * @return nc_crypt() return value.
 */
static int
test_crypt_verify(const char *password, const char *setting, int match_init, int *match)
{
    struct nc_crypt c;
    int rc;

    memset(&c, 0, sizeof c);
    c.action = NC_CRYPT_VERIFY;
    c.match = match_init;

    rc = nc_crypt(password, setting, &c);
    *match = c.match;

    return rc;
}

/**
 * @brief Check that every reference vector is created exactly.
 *
 * @param[in] state Test state.
 */
static void
test_algo_reference(void **state)
{
    char out[NC_CRYPT_BUFSIZE];
    size_t i;

    (void)state;

    for (i = 0; i < (sizeof test_vectors / sizeof *test_vectors); ++i) {
        assert_int_equal(test_crypt_create(test_vectors[i].password, test_vectors[i].setting, out, sizeof out), 0);
        assert_string_equal(out, test_vectors[i].expected);
    }
}

/**
 * @brief Check handling of invalid arguments.
 *
 * @param[in] state Test state.
 */
static void
test_invalid_args(void **state)
{
    char out[NC_CRYPT_BUFSIZE];
    struct nc_crypt c;

    (void)state;

    /* NULL arguments */
    memset(&c, 0, sizeof c);
    c.action = NC_CRYPT_CREATE;
    c.output = out;
    c.output_len = sizeof out;
    assert_int_equal(nc_crypt(NULL, "$6$abc$", &c), -1);
    assert_int_equal(nc_crypt("hello", NULL, &c), -1);
    assert_int_equal(nc_crypt("hello", "$6$abc$", NULL), -1);

    /* no output buffer for hash creation */
    memset(&c, 0, sizeof c);
    c.action = NC_CRYPT_CREATE;
    c.output_len = sizeof out;
    assert_int_equal(nc_crypt("hello", "$6$abc$", &c), -1);
}

/**
 * @brief Check handling of a small output buffer, an unknown action, an unknown
 * hash id and a malformed hash string.
 *
 * @param[in] state Test state.
 */
static void
test_invalid_input(void **state)
{
    static const char *sha512_hello = TEST_HASH_SHA512_HELLO;
    static const char *sha256_rounds_hello = "$5$rounds=1000$abcdefghijklmnop$WrXWnj4kGA329xgo6OuYgg4dCUBFRerEyEW8GtoN6I5";
    char out[NC_CRYPT_BUFSIZE];
    struct nc_crypt c;
    int match;

    (void)state;

    /* an output buffer of the exact size works */
    assert_int_equal(test_crypt_create("hello", "$6$abcdefghijklmnop$", out, strlen(sha512_hello) + 1), 0);
    assert_string_equal(out, sha512_hello);
    assert_int_equal(test_crypt_create("hello", "$5$rounds=1000$abcdefghijklmnop$", out, strlen(sha256_rounds_hello) + 1), 0);
    assert_string_equal(out, sha256_rounds_hello);

    /* an output buffer one byte too small fails before the hash is computed and the buffer is not modified at all */
    memset(out, (char)0xAA, sizeof out);
    assert_int_equal(test_crypt_create("hello", "$6$abcdefghijklmnop$", out, strlen(sha512_hello)), -4);
    assert_int_equal(out[0], (char)0xAA);
    assert_int_equal(out[strlen(sha512_hello) / 2], (char)0xAA);
    assert_int_equal(out[sizeof out - 1], (char)0xAA);

    /* unknown action */
    memset(&c, 0, sizeof c);
    c.action = (enum nc_crypt_action)42;
    assert_int_equal(nc_crypt("hello", "$6$abc$", &c), -1);

    /* unknown hash id */
    assert_int_equal(test_crypt_create("hello", "$2b$abcdefghijklmnop$", out, sizeof out), -2);
    assert_int_equal(test_crypt_create("hello", "$2y$abcdefghijklmnop$", out, sizeof out), -2);
    assert_int_equal(test_crypt_create("hello", "$7$abc$", out, sizeof out), -2);
    assert_int_equal(test_crypt_create("hello", "$x$abc$", out, sizeof out), -2);
    assert_int_equal(test_crypt_create("hello", "$0$password", out, sizeof out), -2);
    assert_int_equal(test_crypt_create("hello", "$6abc$", out, sizeof out), -2);
    assert_int_equal(test_crypt_verify("hello", "$2b$abcdefghijklmnop$hash", 0, &match), -2);

    /* malformed setting string */
    assert_int_equal(test_crypt_create("hello", "", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$6", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "6$abc$", out, sizeof out), -3);

    /* salt characters outside the crypt base64 alphabet [a-zA-Z0-9./] */
    assert_int_equal(test_crypt_create("hello", "$6$a!b@c#$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$1$a!b@c#$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$6$ab cd$", out, sizeof out), -3);
    /* crypt_r(3) tolerates '=' in a "$1$" salt, but the iana-crypt-hash
     * YANG type excludes it as well */
    assert_int_equal(test_crypt_create("hello", "$1$rounds=5$", out, sizeof out), -3);
    /* the whole salt run is validated, even past the truncation length */
    assert_int_equal(test_crypt_create("hello", "$6$abcdefghijklmnop!xyz$", out, sizeof out), -3);
    /* invalid characters in the stored digest of a verification */
    assert_int_equal(test_crypt_verify("hello", "$6$abcdefghijklmnop$vRqpf9WzVv13MKJy4hd5!ALhNQnt4y0RZsj0MrdHWdwA8G8gihD6oj69IwfuemaVekHG0M6jA5HNgthaIaLRR/", 0, &match), -3);
    assert_int_equal(match, 1);

    /* invalid "rounds=" specification */
    assert_int_equal(test_crypt_create("hello", "$5$rounds=abc$abc$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$5$rounds=$abc$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$5$rounds=1x$abc$", out, sizeof out), -3);

    /* "rounds=" out of the valid range [1000, 999999999] */
    assert_int_equal(test_crypt_create("hello", "$5$rounds=0$abc$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$5$rounds=999$abc$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$5$rounds=1000000000$abc$", out, sizeof out), -3);
    assert_int_equal(test_crypt_create("hello", "$6$rounds=99999999999999999999$abc$", out, sizeof out), -3);

    /* no stored digest to verify against */
    assert_int_equal(test_crypt_verify("hello", "$6$abcdefghijklmnop$", 0, &match), -3);
    assert_int_equal(match, 1);
}

/**
 * @brief Check password verification against stored hashes.
 *
 * @param[in] state Test state.
 */
static void
test_verify_password(void **state)
{
    int match;

    (void)state;

    /* correct password of every scheme */
    assert_int_equal(test_crypt_verify("hello", "$1$abcdefgh$rwnEbRiN0agqVgZBovWNQ/", 1, &match), 0);
    assert_int_equal(match, 0);
    assert_int_equal(test_crypt_verify("hello", "$5$rounds=10000$abcdefghijklmnop$gakfHbxNcYmu8/VVGCdhagYkdMmRhzRqQyQhHYWi9k7", 1, &match), 0);
    assert_int_equal(match, 0);
    assert_int_equal(test_crypt_verify("hello", TEST_HASH_SHA512_HELLO, 1, &match), 0);
    assert_int_equal(match, 0);

    /* empty password */
    assert_int_equal(test_crypt_verify("", "$1$$qRPK7m23GJusamGpoGLby/", 1, &match), 0);
    assert_int_equal(match, 0);

    /* wrong password */
    assert_int_equal(test_crypt_verify("hellp", TEST_HASH_SHA512_HELLO, 0, &match), 0);
    assert_int_equal(match, 1);
    assert_int_equal(test_crypt_verify("", TEST_HASH_SHA512_HELLO, 0, &match), 0);
    assert_int_equal(match, 1);
}

/**
 * @brief Check handling of unusual salt formats.
 *
 * @param[in] state Test state.
 */
static void
test_salt_format(void **state)
{
    char out[NC_CRYPT_BUFSIZE];
    int match;

    (void)state;

    /* a '$' in the setting terminates the salt, the rest is the stored digest */
    assert_int_equal(test_crypt_create("hello", "$6$ab$cd$", out, sizeof out), 0);
    assert_string_equal(out, "$6$ab$kCEdajKfECjkWwo5i4GMTY4WW.ADIevHyGdlZb3r8wskFWlOJqWZgemJ96NLPhkdsWWH5zZrOY6OzTC0hpeuU1");

    /* empty salt round-trip */
    assert_int_equal(test_crypt_create("hello", "$6$$", out, sizeof out), 0);
    assert_int_equal(test_crypt_verify("hello", out, 1, &match), 0);
    assert_int_equal(match, 0);
}

/**
 * @brief Check verification against corrupted stored hashes.
 *
 * @param[in] state Test state.
 */
static void
test_corrupt_stored_hash(void **state)
{
    char buf[NC_CRYPT_BUFSIZE];
    int match;

    (void)state;

    /* truncated digest */
    strcpy(buf, TEST_HASH_SHA512_HELLO);
    buf[strlen(buf) - 1] = '\0';
    assert_int_equal(test_crypt_verify("hello", buf, 0, &match), 0);
    assert_int_equal(match, 1);

    /* extended digest */
    strcpy(buf, TEST_HASH_SHA512_HELLO);
    strcat(buf, "x");
    assert_int_equal(test_crypt_verify("hello", buf, 0, &match), 0);
    assert_int_equal(match, 1);

    /* corrupted digest character */
    strcpy(buf, TEST_HASH_SHA512_HELLO);
    buf[60] = (buf[60] == 'A') ? 'B' : 'A';
    assert_int_equal(test_crypt_verify("hello", buf, 0, &match), 0);
    assert_int_equal(match, 1);

    /* character outside the base64 alphabet in the digest */
    strcpy(buf, TEST_HASH_SHA512_HELLO);
    buf[25] = '!';
    assert_int_equal(test_crypt_verify("hello", buf, 0, &match), -3);
    assert_int_equal(match, 1);

    /* no digest at all */
    assert_int_equal(test_crypt_verify("hello", "$6$abcdefghijklmnop$", 0, &match), -3);
    assert_int_equal(match, 1);
}

int
main(void)
{
    const struct CMUnitTest tests[] = {
        cmocka_unit_test(test_algo_reference),
        cmocka_unit_test(test_invalid_args),
        cmocka_unit_test(test_invalid_input),
        cmocka_unit_test(test_verify_password),
        cmocka_unit_test(test_salt_format),
        cmocka_unit_test(test_corrupt_stored_hash),
    };

    return cmocka_run_group_tests(tests, NULL, NULL);
}
